import { Component, OnInit, signal } from '@angular/core';
import { FormsModule } from '@angular/forms';
import { Router } from '@angular/router';
import { Voiture } from '../model/voiture.model';
import { Categorie } from '../model/categorie.model';
import { Voitureservice } from '../services/voiture';

@Component({
  imports: [FormsModule],
  selector: 'app-add-voiture',
  templateUrl: './add-voiture.html',
})
export class AddVoiture implements OnInit {
  categories = signal<Categorie[]>([]);
  newIdCat!: number;
  newVoiture = new Voiture();

  constructor(
    private voitureservice: Voitureservice,
    private router: Router
  ) {}

  ngOnInit(): void {
    this.voitureservice.listeCategorie().subscribe(cats => this.categories.set(cats));
  }

  addVoiture() {
    if (!this.newVoiture.nomVoiture || !this.newIdCat) {
      alert('Veuillez remplir le nom et choisir une catégorie.');
      return;
    }
    const cat = this.categories().find(c => c.idCat == this.newIdCat);
    if (!cat) return;

    this.newVoiture.categorie = cat;
    // the date input gives a "yyyy-MM-dd" string -> convert to Date
    this.newVoiture.dateCreation = new Date(this.newVoiture.dateCreation);

    // the id is generated by MySQL, so it is not sent
    this.voitureservice.ajoutVoiture(this.newVoiture).subscribe({
      next: () => this.router.navigate(['/voitures']),
      error: () => alert("L'ajout a échoué. Vérifiez que le serveur est démarré.")
    });
  }
}